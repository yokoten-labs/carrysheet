#!/usr/bin/env node
// Generates crates/carrysheet-cfb/src/upper_table.rs: the uppercase mapping
// MS-CFB uses to compare entry names, pinned so it does not follow the Rust
// toolchain's Unicode version.
//
// MS-CFB 2.6.4 names the Unicode simple case conversion; its product note
// <3> says Windows Vista and later use Unicode 5.0 with a short list of
// exceptions, and leave code points above U+FFFF as they are. Windows
// writes the files we read, so the table is Unicode 5.0.0's simple
// uppercase (UnicodeData.txt field 12) for the BMP, with those exceptions.
//
// Usage: node scripts/gen-cfb-upper.mjs path/to/UnicodeData.txt
// The file is https://www.unicode.org/Public/5.0.0/ucd/UnicodeData.txt;
// its SHA-256 is checked so a different version cannot slip in.

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SHA256 = 'e458a6cab52182af09cb40defab6d00e6927d51ef7291017647e9c10b3e196b9';
const OUT = join(dirname(fileURLToPath(import.meta.url)), '..', 'crates', 'carrysheet-cfb', 'src', 'upper_table.rs');

// MS-CFB note <3>, Windows Vista and later: [code unit, its uppercase].
// The sigma rows of the note match Unicode 5.0 already.
const WINDOWS = [
  [0x023a, 0x2c65],
  [0x2c65, 0x2c65],
  [0x023e, 0x2c66],
  [0x2c66, 0x2c66],
  [0x03c2, 0x03a3],
  [0x03c3, 0x03a3],
  [0x1fc3, 0x1fc3],
  [0x1fcc, 0x1fc3],
];

const path = process.argv[2];
if (!path) {
  console.error('usage: node scripts/gen-cfb-upper.mjs path/to/UnicodeData.txt (Unicode 5.0.0)');
  process.exit(2);
}
const bytes = readFileSync(path);
const sum = createHash('sha256').update(bytes).digest('hex');
if (sum !== SHA256) {
  console.error(`${path} is not Unicode 5.0.0's UnicodeData.txt (SHA-256 ${sum})`);
  process.exit(1);
}

const map = new Map();
for (const line of bytes.toString('utf8').split('\n')) {
  const f = line.split(';');
  if (f.length < 13 || f[12] === '') continue;
  const from = parseInt(f[0], 16);
  const to = parseInt(f[12], 16);
  if (from > 0xffff || to > 0xffff) continue;
  map.set(from, to);
}
for (const [from, to] of WINDOWS) map.set(from, to);

const rows = [...map].filter(([from, to]) => from !== to).sort((a, b) => a[0] - b[0]);
const hex = (n) => `0x${n.toString(16).toUpperCase().padStart(4, '0')}`;
let body = '';
for (let i = 0; i < rows.length; i += 4) {
  body += `    ${rows.slice(i, i + 4).map(([a, b]) => `(${hex(a)}, ${hex(b)})`).join(', ')},\n`;
}

writeFileSync(
  OUT,
  `// Generated by scripts/gen-cfb-upper.mjs from Unicode 5.0.0 UnicodeData.txt
// with the Windows exceptions of MS-CFB note <3>. Do not edit.

/// (code unit, its uppercase) for every BMP code unit that changes, sorted.
#[rustfmt::skip]
pub(crate) const UPPER: [(u16, u16); ${rows.length}] = [
${body}];
`,
);
console.error(`wrote ${rows.length} mappings to ${OUT}`);
