/// Looks up a function by number.
pub(crate) fn function(index: u16) -> Option<(&'static str, u8, u8)> {
    FUNCTIONS
        .binary_search_by_key(&index, |f| f.0)
        .ok()
        .map(|i| (FUNCTIONS[i].1, FUNCTIONS[i].2, FUNCTIONS[i].3))
}

/// Looks up a command-equivalent function by number.
pub(crate) fn command(index: u16) -> Option<(&'static str, u8, u8)> {
    COMMANDS
        .binary_search_by_key(&index, |f| f.0)
        .ok()
        .map(|i| (COMMANDS[i].1, COMMANDS[i].2, COMMANDS[i].3))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn tables_are_sorted_and_known_entries_match() {
        assert!(FUNCTIONS.windows(2).all(|w| w[0].0 < w[1].0));
        assert!(COMMANDS.windows(2).all(|w| w[0].0 < w[1].0));
        assert_eq!(function(4), Some(("SUM", 0, 30)));
        assert_eq!(function(1).map(|f| f.0), Some("IF"));
        assert_eq!(function(15), Some(("SIN", 1, 1)));
        assert_eq!(function(255).map(|f| f.0), None);
    }
}
