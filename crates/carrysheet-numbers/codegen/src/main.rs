//! Compiles `../proto/*.proto` with protox (a pure-Rust protobuf compiler, so
//! no `protoc` is needed) and writes prost code to `../src/proto/`, and the
//! wire schema the reader checks objects against to `../src/iwa/schema.rs`.
//!
//! Run from `crates/carrysheet-numbers`:
//! `cargo run --manifest-path codegen/Cargo.toml`, then `cargo fmt`.

use std::collections::HashMap;
use std::fmt::Write as _;
use std::{error::Error, fs, path::Path};

use heck::{ToSnakeCase, ToUpperCamelCase};
use prost_types::field_descriptor_proto::{Label, Type};
use prost_types::{DescriptorProto, FileDescriptorSet};

const FILES: &[&str] = &["TSP", "TN", "TSD", "TSWP", "TSCE", "TST"];

fn main() -> Result<(), Box<dyn Error>> {
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("..");
    let proto_dir = crate_dir.join("proto");
    let out_dir = crate_dir.join("src").join("proto");
    let tmp = std::env::temp_dir().join("carrysheet-numbers-codegen");
    fs::create_dir_all(&tmp)?;

    let files: Vec<_> = FILES.iter().map(|f| proto_dir.join(format!("{f}.proto"))).collect();
    let descriptors = protox::compile(&files, [&proto_dir])?;
    let schema = schema(&descriptors)?;

    prost_build::Config::new()
        .out_dir(&tmp)
        // Field names come from Apple's archives; keep the generated docs out.
        .disable_comments(["."])
        .compile_fds(descriptors)?;

    for name in FILES {
        let module = name.to_lowercase();
        let generated = fs::read_to_string(tmp.join(format!("{module}.rs")))?;
        let header = format!(
            "// @generated by codegen/ from proto/{name}.proto. Do not edit by hand.\n\
             // The definitions are derived from numbers-parser (MIT); see THIRD-PARTY.md.\n\n"
        );
        fs::write(out_dir.join(format!("{module}.rs")), header + &generated)?;
    }
    fs::write(crate_dir.join("src").join("iwa").join("schema.rs"), schema)?;
    eprintln!("wrote {} files to src/proto/ and src/iwa/schema.rs", FILES.len());
    Ok(())
}

/// One message: its full protobuf name and its Rust path.
struct Described<'a> {
    full: String,
    rust: String,
    message: &'a DescriptorProto,
}

fn collect<'a>(
    package: &str,
    prefix: &str,
    module: &str,
    messages: &'a [DescriptorProto],
    out: &mut Vec<Described<'a>>,
) {
    for message in messages {
        let name = message.name();
        let full = format!(".{package}.{prefix}{name}");
        let rust = format!("{module}::{}", name.to_upper_camel_case());
        out.push(Described {
            full,
            rust,
            message,
        });
        let nested_module = format!("{module}::{}", name.to_snake_case());
        collect(
            package,
            &format!("{prefix}{name}."),
            &nested_module,
            &message.nested_type,
            out,
        );
    }
}

/// Rust source for `src/iwa/schema.rs`: for every message, its size in
/// memory and the fields that take memory when decoded (sub-messages,
/// strings and bytes, repeated numbers).
fn schema(set: &FileDescriptorSet) -> Result<String, Box<dyn Error>> {
    let mut all = Vec::new();
    for file in &set.file {
        let package = file.package();
        if !FILES.contains(&package) {
            continue;
        }
        collect(package, "", &package.to_lowercase(), &file.message_type, &mut all);
    }
    let index: HashMap<&str, usize> = all.iter().enumerate().map(|(i, d)| (d.full.as_str(), i)).collect();

    let mut out = String::from(
        "// @generated by codegen/ from proto/*.proto. Do not edit by hand.\n\
         // The definitions are derived from numbers-parser (MIT); see THIRD-PARTY.md.\n\
         //\n\
         // For each message: its size in memory and the fields that take memory\n\
         // when prost decodes them. `wire::check` uses it before decoding.\n\n\
         use super::wire::{Described, Field, Kind, Message};\n\
         use crate::proto::{tn, tsce, tsd, tsp, tst, tswp};\n\n\
         pub(crate) static MESSAGES: &[Message] = &[\n",
    );
    for d in &all {
        let mut fields: Vec<(i32, String)> = Vec::new();
        for f in &d.message.field {
            let repeated = f.label() == Label::Repeated;
            let kind = match f.r#type() {
                Type::Message | Type::Group => {
                    let child = index
                        .get(f.type_name())
                        .ok_or_else(|| format!("unknown type {}", f.type_name()))?;
                    format!("Kind::Message({child})")
                }
                Type::String | Type::Bytes => "Kind::Bytes".to_owned(),
                _ if !repeated => continue,
                Type::Fixed32 | Type::Sfixed32 | Type::Float => "Kind::Fixed(4)".to_owned(),
                Type::Fixed64 | Type::Sfixed64 | Type::Double => "Kind::Fixed(8)".to_owned(),
                _ => "Kind::Varint".to_owned(),
            };
            fields.push((
                f.number(),
                format!(
                    "Field {{ number: {}, kind: {kind}, repeated: {repeated} }}",
                    f.number()
                ),
            ));
        }
        fields.sort_by_key(|(n, _)| *n);
        let _ = writeln!(out, "    // {}", &d.full[1..]);
        let _ = writeln!(out, "    Message {{");
        let _ = writeln!(out, "        size: size_of::<{}>(),", d.rust);
        let _ = writeln!(out, "        fields: &[");
        for (_, f) in &fields {
            let _ = writeln!(out, "            {f},");
        }
        let _ = writeln!(out, "        ],");
        let _ = writeln!(out, "    }},");
    }
    out.push_str("];\n\n");
    for (i, d) in all.iter().enumerate() {
        let _ = writeln!(
            out,
            "impl Described for {} {{\n    const SCHEMA: usize = {i};\n}}",
            d.rust
        );
    }
    Ok(out)
}
